export function getTranslation(locale: string): TranslationData {
  const lang = getLanguage(locale);
  const data = TRANSLATIONS[locale] || {
    ...TRANSLATIONS.en,
    pageTitle: `${lang.targetKeyword} – ${lang.name}`,
    h1: lang.targetKeyword,
    metaDescription: `Free online ${lang.targetKeyword}. Calculate your exact age in years, months, days, and live running seconds in ${lang.nativeName} (${lang.name}).`,
    tools: Object.fromEntries(
      Object.entries(TRANSLATIONS.en.tools).map(([key, val]) => [
        key,
        { title: `${val.title} (${lang.nativeName})`, desc: val.desc }
      ])
    )
  };

  return {
    ...data,
    locale: lang.code,
    years: data.years || data.yearsLabel,
    months: data.months || data.monthsLabel,
    days: data.days || data.daysLabel,
    seconds: data.seconds || data.secondsLabel,
  };
}
